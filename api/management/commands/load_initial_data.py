class Command(BaseCommand):
    help = 'Load initial symptoms and diseases data'

    def handle(self, *args, **options):
        self.stdout.write('Loading symptoms...')
        for data in SYMPTOMS_DATA:
            Symptom.objects.get_or_create(
                name=data['name'],
                defaults={
                    'body_part': data['body_part'],
                    'severity_level': data['severity_level'],
                    'description': f"Symptom: {data['name']}",
                }
            )
        self.stdout.write(self.style.SUCCESS(f'Loaded {len(SYMPTOMS_DATA)} symptoms'))

        self.stdout.write('Loading diseases...')
        for data in DISEASES_DATA:
            disease, _ = Disease.objects.get_or_create(
                name=data['name'],
                defaults={
                    'description': data['description'],
                    'severity': data['severity'],
                    'treatments': data['treatments'],
                    'prevention': data['prevention'],
                }
            )
            for symptom_name in data['symptoms']:
                symptom, _ = Symptom.objects.get_or_create(
                    name=symptom_name,
                    defaults={
                        'body_part': next((s['body_part'] for s in SYMPTOMS_DATA if s['name'] == symptom_name), 'General'),
                        'severity_level': next((s['severity_level'] for s in SYMPTOMS_DATA if s['name'] == symptom_name), 'medium'),
                        'description': f"Symptom: {symptom_name}",
                    }
                )
                disease.symptoms.add(symptom)
        self.stdout.write(self.style.SUCCESS(f'Loaded {len(DISEASES_DATA)} diseases'))
